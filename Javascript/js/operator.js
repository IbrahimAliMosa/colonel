//Arithmetic Operators
let x = 5;
let y = 3;
console.log(x + y); // 8
console.log(x - y); // 2
console.log(x * y); // 15
console.log(x / y); // 1.666...
console.log(x % y); // 2
console.log(x ** y); // 125
console.log(++x); // 6
console.log(--y); // 2
console.log(x++); // 6
console.log(y--); // 2
/* the difference between ++x and x++ is that ++x increments the value of x before returning it, while x++ returns the value of x before incrementing it. 
        The same applies to --y and y--.
*/

//Comparison Operators
let a = 10;
let b = 20;
console.log(a == b); // false
console.log(a != b); // true
console.log(a === b); // false
console.log(a !== b); // true
console.log(a > b); // false
console.log(a < b); // true
console.log(a >= b); // false
console.log(a <= b); // true


//Logical Operators
let c = true;
let d = false;
console.log(c && d); // false
console.log(c || d); // true
console.log(!c); // false
